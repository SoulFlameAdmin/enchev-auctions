assert.match(panel,/architectureByDay.get\(task.id\)/);
assert.match(panel,/ТЕХНИЧЕСКА АРХИТЕКТУРА НА/);
assert.match(panel,/const auditedD001:Entry=\{status:"done",test:"pass"/,"Preserve audited D001");
assert.match(center,/readiness|спецификация|спецификации/i);
assert.match(center,/onOpenTask\(day.id\)/);
assert.match(center,/design|architecture\.graph/);
assert.match(center,/NO-GO/);
assert.ok(stylesheet.includes("@media(max-width:720px)"));
assert.doesNotMatch(panel,/\bCopart\b/i,"No competitor brand in public-facing plan source");
assert.doesNotMatch(center,/\bCopart\b/i,"No competitor brand in public-facing blueprint source");
