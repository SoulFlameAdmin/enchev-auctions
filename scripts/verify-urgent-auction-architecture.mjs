import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const load=path=>JSON.parse(readFileSync(path,"utf8"));
const plan=load("app/data/urgent-119-days.json");
const design=load("app/data/urgent-auction-architecture-119-v1.json");
const benchmark=load("app/data/urgent-auction-benchmark-v1.json");
const legal=load("app/data/urgent-legal-foundation-v1.json");
const panel=readFileSync("app/components/UrgentPlan119.tsx","utf8");
const center=readFileSync("app/components/AuctionArchitecture119.tsx","utf8");
const stylesheet=readFileSync("app/components/urgent-auction-architecture.css","utf8");
const ids=new Set(plan.tasks.map(day=>day.id));
const legalIds=new Set(legal.requirements.map(row=>row.id));
assert.equal(plan.tasks.length,119);
assert.equal(plan.taskCount,119);
assert.equal(plan.plannedTeamHours,799);
assert.equal(plan.startsOn,"2026-11-03");
assert.equal(plan.launchDate,"2027-03-01");
assert.equal(design.baseline.dayCount,119);
assert.equal(design.baseline.launchDate,plan.launchDate);
assert.equal(design.baseline.plannedTeamHours,799);
assert.equal(design.baseline.immutable,true);
assert.match(design.referencePolicy,/Public auction-business functionality only/);
assert.equal(design.stages.length,17);
assert.equal(design.days.length,119);
assert.equal(new Set(design.days.map(x=>x.id)).size,119);
assert.equal(design.graph.length,17);
const featureIds=new Set(benchmark.features.map(x=>x.id));
const feeCodes=new Set(benchmark.feeComponents.map(x=>x.code));
const documentCodes=new Set(benchmark.documentWorkflows.map(x=>x.code));
const allFeatures=new Set(),allFees=new Set(),allDocs=new Set();
let signatures=0;
for(let w=1;w<=17;w++){
 const stage=design.stages[w-1];
 const original=plan.tasks.filter(x=>x.week===w);
 assert.equal(stage.week,w);
 assert.match(stage.id,/^ARCH-\d{2}$/);
 assert.equal(stage.phaseDays.length,7);
 assert.deepEqual(stage.phaseDays,original.map(x=>x.id));
 assert.equal(stage.status,"design-specified-not-certified","Blueprint must not claim execution");
 assert.ok(stage.components.length>=3);
 assert.ok(stage.tables.length>=3);
 assert.ok(stage.exitGate.length>20);
}
for(let i=0;i<119;i++){
 const task=plan.tasks[i],day=design.days[i],stage=design.stages[day.week-1];
 assert.equal(day.id,task.id);
 assert.equal(day.date,task.date);
 assert.equal(day.title,task.title);
 assert.equal(day.week,task.week);
 assert.equal(day.owner,task.owner);
 assert.equal(day.priority,task.priority);
 assert.equal(day.plannedHours,task.plannedHours);
 assert.equal(day.baselinePassCriteria,task.passCriteria);
 assert.equal(day.stageId,stage.id);
 assert.equal(day.readiness,"architecture-specified-not-proven","Do not convert documentation into PASS");
 const expected=task.dependency.match(/D\d{3}/g)||[];
 assert.deepEqual(day.dependencyIds,expected);
 if(i>0)assert.deepEqual(day.dependencyIds,[plan.tasks[i-1].id],"Sequential urgent plan dependency must not break");
 assert.ok(day.targetComponents.length>=3);
 assert.ok(day.domainEntities.length>=3);
 assert.ok(day.interfaceContracts.length>=1);
 assert.equal(day.implementationSteps.length,3);
 assert.ok(day.goal.length>9);
 assert.ok(day.testPlan.artifact.length>19);
 assert.match(day.testPlan.positive,/Доказателство:/);
 assert.match(day.testPlan.negative,/Забранена|невалидна/);
 assert.ok(["true","until-signed-GO"].includes(String(day.testPlan.sandboxOnly)));
 const refs=benchmark.features.filter(x=>x.linkedDay===day.id);
 assert.deepEqual(day.featureIds,refs.map(x=>x.id));
 assert.deepEqual(day.priorityFeatureIds,refs.filter(x=>x.priority==="P0").map(x=>x.id));
 for(const id of day.featureIds){assert.ok(featureIds.has(id));allFeatures.add(id);}
 const fees=benchmark.feeComponents.filter(x=>x.linkedDay===day.id);
 assert.deepEqual(day.feeCodes,fees.map(x=>x.code));
 for(const code of day.feeCodes){assert.ok(feeCodes.has(code));allFees.add(code);}
 const docs=benchmark.documentWorkflows.filter(x=>x.linkedDay===day.id);
 assert.deepEqual(day.documentCodes,docs.map(x=>x.code));
 for(const code of day.documentCodes){assert.ok(documentCodes.has(code));allDocs.add(code);}
 for(const legalId of day.legalRequirementIds)assert.ok(legalIds.has(legalId));
 const expectedGates=benchmark.decisionGates.filter(g=>g.byDay===day.id);
 assert.equal(day.signatureGates.length,expectedGates.length);
 signatures+=day.signatureGates.length;
}
assert.equal(allFeatures.size,76);
assert.equal(allFees.size,20);
assert.equal(allDocs.size,17);
assert.equal(signatures,8);
assert.equal(design.scopeSummary.features,allFeatures.size);
assert.equal(design.scopeSummary.fees,allFees.size);
assert.equal(design.scopeSummary.documents,allDocs.size);
assert.equal(design.scopeSummary.signatureGates,signatures);
assert.ok(design.systems.architecturePrinciples.some(x=>/PostgreSQL is authoritative/.test(x)));
assert.ok(design.systems.architecturePrinciples.some(x=>/Fees in ENCHEV remain unapproved/.test(x)));
assert.ok(design.systems.architecturePrinciples.some(x=>/Release gate/.test(x)));
