import { readFileSync, writeFileSync } from "node:fs";

const PLAN_PATH = "app/components/MasterSystemPlanV1.tsx";
const OUTPUT_PATH = "app/generated-master-plan-test-ids.ts";
const source = readFileSync(PLAN_PATH, "utf8");
const startMarker = "const raw: RawPhase[] = ";
const endMarker = "\n\nconst WAVE_LABELS";
const start = source.indexOf(startMarker);
const end = source.indexOf(endMarker, start);

if (start === -1 || end === -1) {
  console.error("MASTER_TEST_IDS: unable to locate frozen raw plan");
  process.exit(1);
}

const literal = source.slice(start + startMarker.length, end).trim().replace(/;$/, "");
let raw;
try {
  raw = Function(`\"use strict\"; return (${literal});`)();
} catch (error) {
  console.error("MASTER_TEST_IDS: unable to parse frozen raw plan", error);
  process.exit(1);
}

if (!Array.isArray(raw)) {
  console.error("MASTER_TEST_IDS: frozen raw plan is not an array");
  process.exit(1);
}

const ids = [];
for (const phase of raw) {
  if (!Array.isArray(phase) || phase.length !== 3 || !Array.isArray(phase[2])) {
    console.error("MASTER_TEST_IDS: malformed phase entry");
    process.exit(1);
  }
  const [phaseId, , items] = phase;
  items.forEach((entry, index) => {
    const [, , kindRaw] = String(entry).split("|");
    if (kindRaw === "test") ids.push(`${phaseId}.${String(index + 1).padStart(2, "0")}`);
  });
}

const body = `// AUTO-GENERATED by scripts/generate-master-test-task-ids.mjs.\n// Do not edit by hand. MASTER SYSTEM PLAN v1.0 FROZEN remains the source of truth.\nexport const MASTER_TEST_TASK_IDS = ${JSON.stringify(ids, null, 2)} as const;\n`;
writeFileSync(OUTPUT_PATH, body, "utf8");
console.log(`MASTER_TEST_IDS generated ${ids.length} test task IDs`);
